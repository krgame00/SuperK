import ts from 'typescript';
import {readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
const modules=new Map();
async function visit(file){
 file=path.resolve(file);const id=path.relative(process.cwd(),file).replaceAll('\\','/');if(modules.has(id))return id;
 modules.set(id,'');const source=await readFile(file,'utf8');
 let code=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.CommonJS}}).outputText;
 const imports=[...code.matchAll(/require\("([^"]+)"\)/g)];
 for(const match of imports){const spec=match[1];if(!spec.startsWith('.')&&!spec.startsWith('@/'))throw new Error(`Unsupported browser dependency ${spec}`);const dependency=spec.startsWith('@/')?path.resolve(spec.slice(2)+'.ts'):path.resolve(path.dirname(file),spec+'.ts');const child=await visit(dependency);code=code.replace(match[0],`require(${JSON.stringify(child)})`);}
 modules.set(id,code);return id;
}
const entry=await visit('chrome-extension/policy-entry.ts');
const output='// Generated by scripts/build-extension-policy.mjs from canonical TypeScript policy. Do not hand edit.\n(()=>{const modules={'+[...modules].sort(([a],[b])=>a.localeCompare(b)).map(([id,code])=>JSON.stringify(id)+':(module,exports,require)=>{\n'+code+'\n}').join(',')+'};const cache={};function require(id){if(cache[id])return cache[id].exports;const m=cache[id]={exports:{}};modules[id](m,m.exports,require);return m.exports;}require('+JSON.stringify(entry)+');})();\n';
await writeFile('chrome-extension/policy.js',output);
